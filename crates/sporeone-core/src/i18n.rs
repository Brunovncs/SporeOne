//! The window's words, in English and Brazilian Portuguese. `{}` in a text is filled in with
//! `fill`.

use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    En,
    Pt,
}

impl Lang {
    /// Portuguese when Windows is in Portuguese.
    pub fn system() -> Lang {
        let lang = std::env::var("SPOREONE_LANG").ok().or_else(user_locale).unwrap_or_default().to_ascii_lowercase();
        if lang.starts_with("pt") { Lang::Pt } else { Lang::En }
    }

    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Pt => "pt",
        }
    }

    pub fn from_code(s: &str) -> Option<Lang> {
        match s {
            "en" => Some(Lang::En),
            "pt" => Some(Lang::Pt),
            _ => None,
        }
    }
}

#[cfg(windows)]
fn user_locale() -> Option<String> {
    crate::win::reg_string(crate::win::Hive::User, r"Control Panel\International", "LocaleName")
}

#[cfg(not(windows))]
fn user_locale() -> Option<String> {
    std::env::var("LANG").ok()
}

pub fn fill(template: &str, value: impl std::fmt::Display) -> String {
    template.replacen("{}", &value.to_string(), 1)
}

